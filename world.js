function resolveWorld(w) { return Object.assign({}, WORLD_DEFAULTS, w); }

function divergedFlags(w) {
  return Object.keys(WORLD_DEFAULTS).filter(k => w[k] !== WORLD_DEFAULTS[k]);
}

