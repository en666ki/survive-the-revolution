/* ---------- сборка и разметка ---------- */

let GLOSS_RE = null;
let GLOSS_TIPS = [];

function buildGloss() {
  const sorted = GLOSSARY.slice().sort((a, b) => b[0].length - a[0].length);
  GLOSS_TIPS = sorted.map(e => e[1]);

  // В JS \b считает границу слова только по латинице, поэтому для кириллицы
  // он бесполезен: «ЧК» после пробела границей не считается. Выкидываем \b
  // из шаблонов и обрамляем каждый своими границами.
  const B = '[А-Яа-яЁёA-Za-z0-9_]';
  const prep = src => src
    .replace(/\\b/g, '')
    // термин может стоять в начале предложения — принимаем и заглавную букву
    .replace(/^([а-яё])/, (m, c) => '[' + c.toUpperCase() + c + ']');
  const wrap = (src, withLookbehind) =>
    '(' + (withLookbehind ? '(?<!' + B + ')' : '') + '(?:' + prep(src) + ')(?!' + B + ')' + ')';

  try {
    GLOSS_RE = new RegExp(sorted.map(e => wrap(e[0], true)).join('|'), 'g');
  } catch (e) {
    // старые браузеры без lookbehind — обходимся одной правой границей
    GLOSS_RE = new RegExp(sorted.map(e => wrap(e[0], false)).join('|'), 'g');
  }
}

// Оборачивает первое вхождение каждого термина в блоке текста.
function annotate(html) {
  if (!GLOSS_RE) buildGloss();
  const seen = new Set();
  return html.replace(GLOSS_RE, function (m) {
    const groups = Array.prototype.slice.call(arguments, 1, GLOSS_TIPS.length + 1);
    let idx = -1;
    for (let i = 0; i < groups.length; i++) if (groups[i] !== undefined) { idx = i; break; }
    if (idx < 0 || seen.has(idx)) return m;
    seen.add(idx);
    const tip = GLOSS_TIPS[idx].replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
    return '<span class="gloss" tabindex="0" data-tip="' + tip + '">' + m + '</span>';
  });
}

/* ---------- всплывающая сноска ---------- */

function initGloss() {
  if (window.__glossReady) return;
  window.__glossReady = true;

  const tip = document.createElement('div');
  tip.className = 'gloss-tip';
  tip.setAttribute('role', 'tooltip');
  tip.hidden = true;
  document.body.appendChild(tip);
  let cur = null;

  function place(el) {
    cur = el;
    tip.textContent = el.getAttribute('data-tip');
    tip.hidden = false;
    tip.style.left = '0px';
    tip.style.top = '0px';
    tip.style.maxWidth = Math.min(340, window.innerWidth - 24) + 'px';
    const r = el.getBoundingClientRect();
    const t = tip.getBoundingClientRect();
    let left = r.left + r.width / 2 - t.width / 2;
    left = Math.max(12, Math.min(left, window.innerWidth - t.width - 12));
    let top = r.bottom + 8;
    if (top + t.height > window.innerHeight - 8) top = r.top - t.height - 8;
    tip.style.left = (left + window.scrollX) + 'px';
    tip.style.top = (top + window.scrollY) + 'px';
  }
  function hide() { cur = null; tip.hidden = true; }

  document.addEventListener('mouseover', e => {
    const g = e.target.closest && e.target.closest('.gloss');
    if (g) place(g);
  });
  document.addEventListener('mouseout', e => {
    const g = e.target.closest && e.target.closest('.gloss');
    if (g && cur === g) hide();
  });
  // тап на телефоне и клик мышью
  document.addEventListener('click', e => {
    const g = e.target.closest && e.target.closest('.gloss');
    if (g) { e.preventDefault(); if (cur === g) hide(); else place(g); }
    else hide();
  });
  document.addEventListener('focusin', e => {
    const g = e.target.closest && e.target.closest('.gloss');
    if (g) place(g);
  });
  document.addEventListener('keydown', e => { if (e.key === 'Escape') hide(); });
  window.addEventListener('scroll', () => { if (cur) place(cur); }, { passive: true });
  window.addEventListener('resize', hide);
}
