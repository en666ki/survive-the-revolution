/* ============================================================
   Часть третья: «Особая папка». Оперуполномоченный УНКВД, 1936–1938.
   Ядро: состояние, эффекты, узлы-концовки, приговор игроку.
   ------------------------------------------------------------
   Механика в двух словах.
   Три счётчика:
     plan  — реализовано по плану (очки за приговоры),
     exc   — «нарушения социалистической законности»: то, что в 1939-м
             пришьют лично вам (сфабрикованные вами дела, выбитые вами
             показания, расстрелянные без всяких оснований),
     susp  — подозрение в отношении вас самого (укрывательство,
             связи, отказ подписывать, заступничество).
   Плюс ins — «папка»: копии рапортов и отказов, единственная страховка.
   exp — сколько дел от вас ожидали (растёт в каждом деле).
   Ключ баланса: дело, которое ведёт Москва, дёшево расстрелять (вина
   не на вас) и смертельно прекратить; дело, слепленное соседом ради
   комнаты, дёшево прекратить и смертельно пустить в расход.
   Поэтому «всех в расход», «всех миловать» и «через одного» проигрывают.
   ============================================================ */

var NODES3 = {};
var CH = { S: null };

function chHas(f) { return CH.S.flags.has(f); }
function chGain(f) { CH.S.flags.add(f); }
function chVal(x) { return (typeof x === 'function' ? x(CH.S) : x); }

/* Конструктор эффекта: E({plan:3, exc:2, susp:1, ins:1}, 'флаг', 'флаг2') */
function E(d) {
  var flags = Array.prototype.slice.call(arguments, 1);
  return function () {
    var s = CH.S;
    if (d) {
      if (d.plan) s.plan += d.plan;
      if (d.exc) s.exc += d.exc;
      if (d.susp) s.susp += d.susp;
      if (d.ins) s.ins += d.ins;
    }
    for (var i = 0; i < flags.length; i++) s.flags.add(flags[i]);
  };
}

