var CHEK_WORDS = {
  pace: function (p) {
    if (p <= -10) return 'провален';
    if (p <= -5) return 'отстаёте';
    if (p <= 3) return 'вровень';
    if (p <= 9) return 'с превышением';
    return 'в передовиках';
  },
  exc: function (v) {
    if (v <= 6) return 'чисто';
    if (v <= 16) return 'есть эпизоды';
    if (v <= 28) return 'набирается том';
    return 'хватит на приговор';
  },
  susp: function (v) {
    if (v <= 5) return 'вне подозрений';
    if (v <= 14) return 'есть отметки';
    if (v <= 26) return 'заведён формуляр';
    return 'разрабатывают';
  },
};

/* Итоговый вердикт 1939–1940 года. Порядок проверок = порядок,
   в котором вас берут: сначала за своих, потом за перегибы. */
/* Чистым по обоим счётчикам стать нельзя: минимально достижимая сумма
   exc+susp при выполнимом плане — 38. Поэтому выживание требует не
   безгрешности, а точности: держать сумму у самой границы возможного,
   не завалив ни план, ни папку. */
function chVerdict(s) {
  var pace = s.plan - s.exp;
  if (pace <= -9) return 'e_ch_saboteur';         // «покрывал врагов»
  if (s.susp >= 34) return 'e_ch_spy';            // «участник заговора в органах»
  if (s.exc >= 34) return 'e_ch_vmn';             // расстрел за перегибы
  if (pace >= 12 && s.exc >= 30) return 'e_ch_vmn';
  if (s.exc >= 26 || s.susp >= 26) return 'e_ch_lager'; // работы
  if (s.ins >= 5 && pace >= -6 && pace <= 4 && (s.exc + s.susp) <= 42) return 'e_ch_alive';
  return 'e_ch_ssylka';                           // ссылка, увольнение
}

